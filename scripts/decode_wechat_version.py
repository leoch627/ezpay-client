"""
推导微信版本号编码。

已知：
  注册表 Version 原始值 0xF254200D  ->  显示 4.1.48.13   （REAL_DATA / 逆向报告）
  本机实测              242.84.28.53 ->  应为 4.1.12.53

逐个字节看：
  0xF254200D = F2 54 20 0D
  4.1.48.13  = 04 01 30 0D     （48 = 0x30, 13 = 0x0D）

  242.84.28.53 = F2 54 1C 35
  4.1.12.53    = 04 01 0C 35    （12 = 0x0C, 53 = 0x35）

观察：原始值的每个字节，都是「真实值 | 0xF0」（高 4 位被置 1）？
  F2 = 04 | F0 = F4  ✗ 不对

再试：低 7 位？
  F2 & 0x7F = 0x72 = 114  ✗

试试「每个字节减去 0xEE」？
  F2 - EE = 04 ✓
  54 - EE = 66  ✗

换个思路：取低 4 位 + ...
  F2 低4位 = 2, 真实是 4  ✗

再看：
  原始 F2 54 20 0D
  目标 04 01 30 0D

  F2 -> 04 : 差 0xEE
  54 -> 01 : 差 0x53
  20 -> 30 : 差 +0x10
  0D -> 0D : 相同

第二组：
  原始 F2 54 1C 35
  目标 04 01 0C 35
  F2 -> 04 : 差 0xEE
  54 -> 01 : 差 0x53
  1C -> 0C : 差 0xF0
  35 -> 35 : 相同

24 位组合：字节 2 的低 2 位是 build 的高 2 位？
  0x20 = 0010 0000, 0x30 = 0011 0000 -> build 48
  0x1C = 0001 1100, 0x0C = 0000 1100 -> build 12
  0x20 & 0x3F = 0x20 = 32, +16 = 48 ✓
  0x1C & 0x3F = 0x1C = 28, ... 28-16=12 ✓
  所以 build = (byte2 & 0x3F) ± 16? 规律不稳。

更可能：整个 32 位是一个「打包」值，微信自己有一套编码。
逆向报告里已明确写了：
  "0xF254200D  → 242, 84, 32, 13 若按 (major<<24)|(minor<<16)|(build<<8)|rev 不匹配"
  "实际对应 4.1.48.13 — 说明经过特定编码/查表"

结论：这是**专有编码**，不是简单位运算。逆向包自己也没解出来。

因此我们的实现不应该去猜这个编码，而应该：
  1. 优先读注册表的字符串版本（如果有）
  2. 退而读 exe 的文件版本（GetFileVersionInfo）
"""
import struct
import sys


def show(raw):
    b = struct.pack(">I", raw)
    print(f"  raw=0x{raw:08X}  bytes={b.hex(' ')}")


print("已知样本：")
show(0xF254200D)
print("   -> 显示 4.1.48.13")
show(0xF2541C35)
print("   -> 显示 4.1.12.53")
print()
print("结论：无可行的纯位运算解码，改用文件版本信息。")
